#!/usr/bin/env python3
# Generate the group READMEs (OEIS/, NT/, GEO/, COM/), the methods index
# and per-method problem lists, and the status table in the top README.
# Sources of truth: problems.jsonl (run tools/manifest.py first) and each
# problem's own README.md. Generated text sits between marker comments, so
# hand-written parts of README.md and methods/*/README.md are kept.
#
# Usage: python3 -I tools/build_readmes.py
#
import json, os, re

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(HERE)

GROUPS = [
  ('OEIS', 'OEIS conjectures', 'Conjecture comments in the On-Line Encyclopedia of Integer Sequences (list: OEIS wiki, Talk:Conjectures/List). OEIS text is quoted under CC BY-SA 4.0 with the A-number as attribution.'),
  ('NT',   'Guy, Unsolved Problems in Number Theory', 'R. K. Guy, *Unsolved Problems in Number Theory*, 3rd ed., Springer 2004. Statements are paraphrased with the section number.'),
  ('GEO',  'Croft, Falconer, Guy, Unsolved Problems in Geometry', 'H. T. Croft, K. J. Falconer, R. K. Guy, *Unsolved Problems in Geometry*, Springer 1991. Statements are paraphrased with the section number.'),
  ('COM',  'Coman, Conjectures on Fermat Pseudoprimes', 'M. Coman, *Two Hundred Conjectures and One Hundred and Fifty Open Problems on Fermat Pseudoprimes*, 2013. C = conjecture (part one), P = open problem (part four). Statements are paraphrased.'),
]
CATS = [
  ('scan resolution', 'Resolved by this project'),
  ('answered elsewhere; confirmed or written up here', 'Answered in the literature; written up or confirmed here'),
  ('disputed or partial; not a resolution', 'Disputed or only partly answered (not counted as resolutions)'),
  ('bound improved; problem still open', 'Bounds improved (the problem stays open)'),
]
BEGIN, END = '<!-- generated by tools/build_readmes.py -->', '<!-- end generated -->'


def natkey(s):
  return [int(t) if t.isdigit() else t for t in re.split(r'(\d+)', s)]


def parse(path):
  s = open(path, encoding='utf-8').read()
  m = re.match(r'#\s*(.*)', s)
  title = m.group(1).strip() if m else ''
  if ':' in title:
    title = title.split(':', 1)[1].strip()
  sec = {}
  for m in re.finditer(r'\*\*([A-Z][A-Za-z ]+?)\.?\*\*\s*(.*?)(?=\n\*\*[A-Z][A-Za-z ]+?\.?\*\*|\n## |\Z)', s, re.S):
    sec[m.group(1).strip()] = m.group(2).strip()
  return title, sec


def cell(t):
  t = re.sub(r'\s+', ' ', t or '').strip()
  return t.replace('|', '\\|').replace('*', '\\*').replace('_', '\\_')


def relink(text, prefix):
  # Links in a problem README are relative to its directory; re-root them.
  #
  def f(m):
    t = m.group(1)
    if re.match(r'[a-z]+:|#|/', t):
      return m.group(0)
    return '](%s)' % os.path.normpath(os.path.join(prefix, t))
  return re.sub(r'\]\(([^)\s]+)\)', f, text)


def lean_cell(e, rel):
  L = e.get('lean')
  link = ( '[%s](%s)' % ('%s', os.path.relpath(L, rel)) if (L and os.path.exists(L)) else None )
  rv, ls = e.get('review'), e.get('lean_status')
  if   rv == 'lean-proof':      txt = 'full proof'
  elif rv == 'lean-witness':    txt = 'witness'
  elif ls == 'needs-mathlib':   txt = 'needs Mathlib'
  elif ls == 'checked':         txt = 'checked'
  else:                         txt = '—'
  return ( (link % txt) if (link and (txt != '—')) else txt )


def pa_cell(e):
  pa = e.get('prior_art') or {}
  v = pa.get('verdict', '—')
  return v + ( ' (immediate)' if pa.get('immediate') and v == 'new' else '' )


def method_cell(e, rel):
  return ', '.join('[%s](%s)' % (m, os.path.relpath('methods/%s/README.md' % m, rel)) for m in e.get('methods', [])[:2])


def group_readme(src, name, about, ents):
  out = ['# %s' % name, '', about, '']
  n = {c: [e for e in ents if e['category'] == c] for c, _ in CATS}
  sc = n[CATS[0][0]]
  out += ['%d entries: %d resolved by this project, %d answered elsewhere, %d disputed or partial.' %
          (len(ents), len(sc), len(n[CATS[1][0]]), len(n[CATS[2][0]])), '']
  out += ['Of the %d resolutions: %d proved in full in Lean, %d with the finite facts (witnesses) checked in Lean '
          'and the remaining steps on paper, %d on paper only (re-derived by a second reader; %d of these need Mathlib '
          'to formalise).' % (len(sc), sum(e['review'] == 'lean-proof' for e in sc), sum(e['review'] == 'lean-witness' for e in sc),
          sum(e['review'] not in ('lean-proof', 'lean-witness') for e in sc),
          sum((e['review'] not in ('lean-proof', 'lean-witness')) and (e['lean_status'] == 'needs-mathlib') for e in sc)), '']
  out += ['Columns: **Lean** says how far Lean checks the result (`full proof`: the whole statement; `witness`: the '
          'finite facts, with the steps outside Lean named in the problem README; `needs Mathlib`: written proof only). '
          '**Prior art** (review 2026-11-04, sources in each problem README): `new` = no source found stating the answer, `partly-known`, `known`; "(immediate)" = follows in a few lines from a known theorem. **Verdict**: proved, disproved, or trivial/misstated. **Result**: one-line summary. **Method** links to [methods/](../methods/README.md). Each problem directory holds the README '
          '(source, reading, result, argument, evidence, review level, prior art), the Lean file and `certificate/` scripts.', '']
  for c, heading in CATS:
    if not n[c]:
      continue
    out += ['## %s' % heading, '', '| Problem | Verdict | Result | Lean | Prior art | Method |', '|---|---|---|---|---|---|']
    for e in n[c]:
      rest = e['id'].split('-', 1)[1]
      title, _ = parse(os.path.join(e['dir'], 'README.md'))
      out.append('| [%s](%s/) | %s | %s | %s | %s | %s |' % (rest, rest, cell(e['result']), cell(title), lean_cell(e, src), pa_cell(e), method_cell(e, src)))
    out.append('')
  out += ['## Short proofs', '', 'Copied from each problem README (source paraphrase, result, argument).', '']
  for c, _ in CATS:
    for e in n[c]:
      rest = e['id'].split('-', 1)[1]
      title, sec = parse(os.path.join(e['dir'], 'README.md'))
      out += ['### [%s](%s/): %s' % (rest, rest, title), '']
      for k in ('Source', 'Reading', 'Result', 'Argument', 'Argument and evidence'):
        if k in sec:
          out += ['**%s.** %s' % (k, relink(sec[k], rest)), '']
      out += ['Lean: %s.' % lean_cell(e, src), '']
  return '\n'.join(out) + '\n'


def uses(e, mid):
  # The two cross-cutting entries are derived, not tagged: every problem
  # with a checked Lean file, and every problem whose README records a
  # reading choice.
  #
  if mid == 'lean-certificate':
    return (e.get('lean_status') == 'checked')
  if mid == 'reading-the-statement':
    return ('Reading' in parse(os.path.join(e['dir'], 'README.md'))[1])
  return (mid in e.get('methods', []))


def replace_block(path, body):
  s = open(path, encoding='utf-8').read()
  i, j = s.index(BEGIN), s.index(END)
  open(path, 'w', encoding='utf-8').write(s[:i + len(BEGIN)] + '\n' + body.rstrip() + '\n' + s[j:])


def main():
  ents = [json.loads(l) for l in open('problems.jsonl', encoding='utf-8') if l.strip()]
  ents.sort(key=lambda e: natkey(e['id']))
  for src, name, about in GROUPS:
    g = [e for e in ents if e['id'].startswith(src + '-')]
    open(os.path.join(src, 'README.md'), 'w', encoding='utf-8').write(group_readme(src, name, about, g))

  # Methods: index table and per-method problem lists.
  #
  meths = json.load(open('methods/methods.json', encoding='utf-8'))
  rows = ['| Method | Role | Applies when | Problems |', '|---|---|---|---|']
  for m in meths:
    used = [e for e in ents if uses(e, m['id'])]
    rows.append('| [%s](%s/README.md) | %s | %s | %d |' % (m['name'], m['id'], m['role'], cell(m['cue']), len(used)))
    lines = ['%d problems (primary method first in each problem\'s list).' % len(used), '']
    for e in used:
      rest = e['id'].split('-', 1)[1]
      title, _ = parse(os.path.join(e['dir'], 'README.md'))
      lines.append('- [%s](../../%s/README.md): %s%s' % (e['id'], e['dir'], title,
                   ( '' if e['category'] == 'scan resolution' else ' (%s)' % e['category'] )))
    replace_block(os.path.join('methods', m['id'], 'README.md'), '\n'.join(lines) if used else 'None tagged yet.')
  replace_block('methods/README.md', '\n'.join(rows))

  # Status table in the top README.
  #
  rows = ['| source | entries | resolved here | full Lean proof | Lean witness | paper only | needs Mathlib | answered elsewhere | disputed or partial |',
          '|---|---|---|---|---|---|---|---|---|']
  tot = [0] * 8
  for src, name, _ in GROUPS:
    g = [e for e in ents if e['id'].startswith(src + '-')]
    sc = [e for e in g if e['category'] == CATS[0][0]]
    v = [len(g), len(sc), sum(e['review'] == 'lean-proof' for e in sc), sum(e['review'] == 'lean-witness' for e in sc),
         sum(e['review'] not in ('lean-proof', 'lean-witness') for e in sc),
         sum((e['review'] not in ('lean-proof', 'lean-witness')) and (e['lean_status'] == 'needs-mathlib') for e in sc),
         sum(e['category'] == CATS[1][0] for e in g), sum(e['category'] == CATS[2][0] for e in g)]
    tot = [a + b for a, b in zip(tot, v)]
    rows.append('| [%s](%s/README.md) | %s |' % (src, src, ' | '.join(map(str, v))))
  rows.append('| total | %s |' % ' | '.join(map(str, tot)))
  rows += ['', 'Prior art of the resolutions by this project (review 2026-11-04):', '',
           '| source | new | new (immediate) | partly known | known |', '|---|---|---|---|---|']
  for src, name, _ in GROUPS:
    sc = [e for e in ents if e['id'].startswith(src + '-') and e['category'] == CATS[0][0]]
    pv = [(e.get('prior_art') or {}) for e in sc]
    rows.append('| %s | %d | %d | %d | %d |' % (src, sum(p.get('verdict') == 'new' and not p.get('immediate') for p in pv),
                sum(p.get('verdict') == 'new' and bool(p.get('immediate')) for p in pv),
                sum(p.get('verdict') == 'partly-known' for p in pv), sum(p.get('verdict') == 'known' for p in pv)))
  replace_block('README.md', '\n'.join(rows))
  print('ok', len(ents))


if __name__ == '__main__':
  main()
